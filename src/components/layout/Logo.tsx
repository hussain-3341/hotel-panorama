import Image from "next/image";
import clsx from "clsx";
import markLight from "../../../public/brand/logo-mark-light-480.png";
import markDark from "../../../public/brand/logo-mark-dark-480.png";
import fullLight from "../../../public/brand/logo-full-light-480.png";
import fullDark from "../../../public/brand/logo-full-dark-480.png";

const SOURCES = {
  mark: { light: markLight, dark: markDark },
  full: { light: fullLight, dark: fullDark },
};

type Props = {
  className?: string;
  /** "light" = ivory lettering for dark backgrounds; "dark" for light backgrounds. */
  tone?: "light" | "dark";
  /** "mark" = sunburst + name (navigation); "full" adds the flourish and "Rooms – Banquet". */
  variant?: "mark" | "full";
  priority?: boolean;
  /** Rendered width in CSS pixels, used to pick the right image size. */
  sizes?: string;
};

/** The official Hotel Panorama logo (generated by `npm run logo`). */
export function Logo({ className, tone = "light", variant = "mark", priority, sizes = "160px" }: Props) {
  return (
    <Image
      src={SOURCES[variant][tone]}
      alt="Hotel Panorama — Rooms & Banquet"
      priority={priority}
      sizes={sizes}
      unoptimized
      className={clsx("h-auto w-auto select-none", className)}
    />
  );
}
